
def suma(a,b):
    return a+b 
    
def resta(a,b):
    return a-b

def producto(a,b):
    return a*b

def potencia(a,b):
    return a**b

def division(a,b):
    return a//b

def modulo(a,b):
    return a%b

def es_par(a:int):
    if a%2==0:
        return f"{a} es par"
    else: 
        return f"{a} es impar"
